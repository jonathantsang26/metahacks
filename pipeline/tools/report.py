"""Generate docs/RESULTS.md from the committed outputs, so every number in it is reproducible.

Reads, per fire: eval/ignition_synthetic.json, eval/ignition_holdout.json, eval/wind_ablation.json,
ignition.json, exposure_stats.json, weather_station.json, wind_field.json, severity_stats.json,
arrival_meta.json, perimeters.geojson, aoi.json, and eval/analyst.json when it exists.

Run: uv run python -m tools.report   (or: make report)
"""

from __future__ import annotations

import json
from pathlib import Path

from ember.config import REPO_DIR, load_fire

FIRES = ["eaton", "palisades"]
OUT = REPO_DIR / "docs" / "RESULTS.md"
README = REPO_DIR / "README.md"
HEADLINE_START = "<!-- headline:start (generated by make report; do not edit) -->"
HEADLINE_END = "<!-- headline:end -->"


def read(fire, name):
    path = fire.out_dir / name
    return json.loads(path.read_text()) if path.exists() else None


def fmt_min(m: float) -> str:
    return f"{m / 60:.1f} h" if abs(m) >= 120 else f"{m:.0f} min"


def synthetic_section(fire) -> list[str]:
    syn = read(fire, "eval/ignition_synthetic.json")
    if not syn:
        return [f"*No synthetic benchmark for {fire.name} yet.*", ""]
    c = syn["config"]
    scenarios = [("all perimeters (as the app fits)", syn.get("summary_all_observations"), syn.get("calibration_all_observations")),
                 (f"first {c['holdout_first_n']} held out (stress test)", syn["summary"], syn.get("calibration"))]
    rows = [
        f"**{fire.name}**: {syn['summary']['n']} synthetic ignitions; observation delays after ignition "
        f"{', '.join(f'{x:g}' for x in c['schedule_h_after_ignition'])} h.",
        "",
        "| Metric | Fit on | Back-trace median | Back-trace p90 | Baseline median | Baseline p90 | Back-trace better |",
        "|---|---|---|---|---|---|---|",
    ]
    for label, s, _ in scenarios:
        if not s:
            continue
        d = s["distance_m"]
        rows.append(f"| Ignition location error | {label} | {d['backtrace']['median']:,.0f} m | {d['backtrace']['p90']:,.0f} m | "
                    f"{d['baseline_first_footprint_centroid']['median']:,.0f} m | {d['baseline_first_footprint_centroid']['p90']:,.0f} m | "
                    f"{s['backtrace_beats_baseline']['distance']:.0%} of cases |")
    for label, s, _ in scenarios:
        if not s:
            continue
        t = s["start_time_error_min"]
        rows.append(f"| Start-time error | {label} | {fmt_min(t['backtrace']['median'])} | {fmt_min(t['backtrace']['p90'])} | "
                    f"{fmt_min(t['baseline_area_backcast']['median'])} | {fmt_min(t['baseline_area_backcast']['p90'])} | "
                    f"{s['backtrace_beats_baseline']['time']:.0%} of cases |")
    rows += [
        "",
        f"Truth physics differs from the inverted model: {c['truth_perturbation']}. "
        "Location baseline = centroid of the first footprint the fit sees; time baseline = linear back-extrapolation of sqrt(area).",
        "",
    ]
    for label, _, cal in scenarios:
        rows += calibration_lines(cal, label)
    return rows


def calibration_lines(cal, label: str) -> list[str]:
    if not cal:
        return []
    t = cal["test_coverage"]
    reached = "" if cal["reached_on_calibration_half"] else " (the 90% target was not reached on the calibration half; this is the widest setting tried)"
    return [
        f"Uncertainty calibration, {label}: posterior temperature tau = {cal['tau_h']:g} h, chosen on the {cal['calibration_cases']} "
        f"even-numbered cases{reached}. On the {cal['test_cases']} odd-numbered cases it never saw, the 90% radius "
        f"(median {cal['median_test_r90_m']:,.0f} m) contains the true ignition in {t['distance']:.0%} of cases and the "
        f"90% start-time interval (median width {cal['median_test_t90_width_h']:g} h) contains the true start in {t['time']:.0%}.",
        "",
    ] + shown_lines(cal.get("test_start_time_shown"))


def shown_lines(shown) -> list[str]:
    """How the product's identifiability rule would have behaved on the unseen synthetic cases."""
    if not shown:
        return []
    if not shown["cases"]:
        return [f"The 6 h identifiability rule would have withheld the start time in all {shown['of']} of those cases.", ""]
    return [f"The 6 h identifiability rule would have shown a start time in {shown['cases']} of those {shown['of']} cases; "
            f"in those, the median start-time error is {fmt_min(shown['median_time_err_min'])} (worst "
            f"{fmt_min(shown['max_time_err_min'])}) and the interval contains the truth in "
            f"{shown['interval_contains_truth']:.0%}.", ""]


def holdout_section(fire) -> list[str]:
    h = read(fire, "eval/ignition_holdout.json")
    ign = read(fire, "ignition.json")
    if not h:
        return []
    e = h.get("errors", {})
    rows = [
        f"**{fire.name}**: fit on {len(h['fit_observations'])} perimeters from {h['fit_observations'][0]}; "
        f"held out {', '.join(x['t'] for x in h['held_out'])}.",
        "",
        "| | Back-trace | Baseline |",
        "|---|---|---|",
    ]
    est = h["estimate"]
    if e:
        yes = lambda b: "yes" if b else "no"
        rows += [
            f"| Distance to CAL FIRE's reported location | {e['backtrace_distance_m']:,.0f} m | {e['baseline_distance_m']:,.0f} m |",
            f"| Start time vs CAL FIRE's official start | {fmt_min(e['backtrace_time_error_min'])} | {fmt_min(e['baseline_time_error_min'])} |",
        ]
        if "reference_within_r90" in e:
            rows += [
                f"| Reported location inside the 90% radius ({est['r90_m']:,.0f} m) | {yes(e['reference_within_r90'])} | – |",
                f"| Official start inside the 90% interval ({est['t90'][0]} – {est['t90'][1]}) | {yes(e['reference_within_t90'])} | – |",
            ]
    rows += [f"| IoU with held-out perimeter {x['t']} | {x['iou']:.2f} | – |" for x in h["held_out"]]
    rows.append("")
    if "timing" in est:
        rows += [timing_line("Hold-out fit", est["timing"]), ""]
    if ign:
        used = (f"{ign['observations_used']} of {ign['perimeters_total']} perimeters, those within {ign['fit_horizon_h']} h "
                "of the first" if "perimeters_total" in ign else "all perimeters")
        rows.append(f"Full fit ({used}): estimate {ign['map']['lat']:.5f}, {ign['map']['lon']:.5f} at {ign['map']['t']}, "
                    f"spread-rate scale k = {ign['map']['k']}"
                    + (f", length-to-breadth cap {ign['map']['lb_max']:g}" if "lb_max" in ign["map"] else "")
                    + f", 90% radius {ign.get('r90_m', 0):,.0f} m, "
                    f"90% start interval {' – '.join(ign.get('t90', []))}, {ign['candidates_evaluated']:,} candidates; "
                    f"modeled vs observed footprint IoU {', '.join(f'{v:.2f}' for v in ign['modeled_vs_observed_iou'])}.")
        if "timing" in ign:
            rows += ["", timing_line("Full fit", ign["timing"])]
        rows.append("")
    return rows


def timing_line(what: str, tm: dict) -> str:
    if tm["identifiable"]:
        return f"{what}: start time identifiable (90% interval {tm['interval90_width_h']:g} h wide)."
    return f"{what}: **start time not identifiable**: {'; '.join(tm['reasons'])}. The timeline omits the estimated start."


def exposure_section(fire) -> list[str]:
    st = read(fire, "exposure_stats.json")
    if not st:
        return []
    rows = [
        f"**{fire.name}**: {st['n']:,} exposed residences, {st['destroyed']:,} destroyed; strata split at the median gust "
        f"at arrival ({st['gust_split_mph']} mph; {st.get('gust_source', 'weather.json')}) × distance to wildland."
        + (f" {st['arrival_imputed']['n']:,} of the homes lie just outside the burned cells and take the nearest burned "
           "cell's arrival time." if "arrival_imputed" in st else ""),
        "",
        "| Feature contrast | n | Mantel–Haenszel OR (95% CI) | Unknown on destroyed / surviving homes |",
        "|---|---|---|---|",
    ]
    for c in st["contrasts"]:
        ci = f"{c['or']:.2f} ({c['ci95'][0]:.2f}–{c['ci95'][1]:.2f})" if c["or"] else "n/a"
        u = c["unknown_rate"]
        rows.append(f"| {c['label']} | {c['n']:,} | {ci} | {u['destroyed']:.0%} / {u['surviving']:.0%} |")
    rows += ["", "OR < 1: the first group was destroyed less often than the second within the same exposure strata. "
             "Associations, not causal effects.", ""]
    return rows


def ablation_section(fire) -> list[str]:
    ab = read(fire, "eval/wind_ablation.json")
    if not ab:
        return []
    names = {"field": "HRRR 3 km field", "uniform": "HRRR, one uniform wind (domain mean)", "era5": "ERA5, one point"}
    rows = [f"**{fire.name}**", "",
            "| Wind in the spread model | Fit loss (h) | Mean footprint IoU | Spread-rate scale k | Estimated start |",
            "|---|---|---|---|---|"]
    for key, v in ab["variants"].items():
        rows.append(f"| {names.get(key, key)} | {v['loss_h']:.2f} | {v['mean_iou']:.2f} | {v['k']:g}"
                    f"{' (ceiling)' if v['k_at_ceiling'] else ''} | {v['t']} |")
    return rows + ["", ab["note"], ""]


def data_section(fire) -> list[str]:
    aoi, meta = read(fire, "aoi.json"), read(fire, "arrival_meta.json")
    ws, sev = read(fire, "weather_station.json"), read(fire, "severity_stats.json")
    per = read(fire, "perimeters.geojson")
    rows = [f"**{fire.name}**"]
    if per and meta:
        rows.append(f"- {len(per['features'])} timed perimeters kept; arrival raster burns {meta['burned_acres']:,.0f} acres "
                    f"vs CAL FIRE's official {aoi['official']['final_acres']:,.0f}.")
    if ws and "comparison_model_at_station" in ws:
        h, e = ws["comparison_model_at_station"], ws.get("comparison_era5_seamless_at_station")
        rows.append(f"- Weather models vs the {ws['station']} ({ws.get('name', '')}) airport station, each at the station's own "
                    f"location: HRRR hourly wind r = {h['wind_corr']:.2f}, RH r = {h['rh_corr']:.2f}, peak gust "
                    f"{h['max_gust_model_mph']:.0f} mph"
                    + (f"; ERA5 r = {e['wind_corr']:.2f}, RH r = {e['rh_corr']:.2f}, peak gust {e['max_gust_model_mph']:.0f} mph" if e else "")
                    + f"; station peak gust {h['max_gust_station_mph']:.0f} mph.")
    wf = read(fire, "wind_field.json")
    if wf:
        sp_ = wf["spread"]
        rows.append(f"- HRRR wind field: {wf['rows']}×{wf['cols']} points ({sp_['distinct_wind_series']} distinct series); "
                    f"peak gust ranges {sp_['peak_gust_range_mph'][0]:.0f}–{sp_['peak_gust_range_mph'][1]:.0f} mph across points.")
    if sev and "perimeter" in sev:
        p = sev["perimeter"]
        rows.append(f"- AVIRIS-3 dNBR covers {p['coverage']:.0%} of the final perimeter "
                    f"({p['covered_acres']:,.0f} of {p['area_acres']:,.0f} acres).")
    rows.append("")
    return rows


def analyst_section(fires) -> list[str]:
    rows = []
    for fire in fires:
        a = read(fire, "eval/analyst.json")
        if not a:
            rows.append(f"- **{fire.name}**: not run yet. The analyst eval (`cd web && npm run eval:analyst -- --fire {fire.id}`) "
                        f"needs `MODEL_API_KEY`; its ground truth is computed from the data files "
                        f"(`npm run eval:analyst -- --truth --fire {fire.id}`).")
            continue
        keys = ("accuracy", "time_accuracy", "number_accuracy", "decline_accuracy", "citation_validity", "n", "model", "date")
        rows.append(f"- **{fire.name}**: " + ", ".join(f"{k} {a.get(k)}" for k in keys if k in a))
    return rows + [""]


def headline(fires) -> list[str]:
    """The README's headline table: every number read from the committed eval files."""
    def cells(fn):
        out = []
        for f in fires:
            try:
                out.append(fn(f))
            except (KeyError, TypeError, IndexError, ValueError, StopIteration):
                out.append("n/a")
        return " | ".join(out)

    syn = lambda f: read(f, "eval/ignition_synthetic.json")
    ign = lambda f: read(f, "ignition.json")
    hold = lambda f: read(f, "eval/ignition_holdout.json")
    ab = lambda f: read(f, "eval/wind_ablation.json")["variants"]
    ex = lambda f: {c["feature"]: c for c in read(f, "exposure_stats.json")["contrasts"]}
    ws = lambda f: read(f, "weather_station.json")

    def dist(s):
        d = s["distance_m"]
        return f"{d['backtrace']['median']:,.0f} m vs {d['baseline_first_footprint_centroid']['median']:,.0f} m"

    def time(s):
        t = s["start_time_error_min"]
        return f"{fmt_min(t['backtrace']['median'])} vs {fmt_min(t['baseline_area_backcast']['median'])}"

    def shown(f):
        c = syn(f)["calibration_all_observations"]
        x = c["test_start_time_shown"]
        return (f"{x['cases']} of {x['of']}" + (f", median error {fmt_min(x['median_time_err_min'])}" if x["cases"] else ""))

    def coverage(f):
        c = syn(f)["calibration_all_observations"]
        return (f"{c['test_coverage']['distance']:.0%} / {c['test_coverage']['time']:.0%} "
                f"(radius {c['median_test_r90_m']:,.0f} m, interval {c['median_test_t90_width_h']:g} h)")

    def real_start(f):
        i, a = ign(f), read(f, "aoi.json")["official"]["incident"]
        if not i["timing"]["identifiable"]:
            return "withheld (not identifiable)"
        from steps.s06_arrival import parse_t
        dt = (parse_t(i["map"]["t"]) - parse_t(a["start_utc"])).total_seconds() / 60
        return f"{i['map']['t'][11:16]}Z, {fmt_min(dt)} from CAL FIRE's {a['start_utc'][11:16]}Z"

    def wind(f):
        v = ab(f)
        before = next(x for k, x in v.items() if k.startswith("era5_lb"))
        return (f"IoU {v['field']['mean_iou']:.2f}, k {v['field']['k']:g} vs IoU {before['mean_iou']:.2f}, "
                f"k {before['k']:g}{' (ceiling)' if before['k_at_ceiling'] else ''}")

    def station(f):
        w = ws(f)
        return (f"r {w['comparison_model_at_station']['wind_corr']:.2f} vs "
                f"{w['comparison_era5_seamless_at_station']['wind_corr']:.2f}")

    def outside(f):
        return f"{ign(f)['reference_outside_first_footprint_m']:,.0f} m"

    def odds(f, feature):
        c = ex(f)[feature]
        return f"{c['or']:.2f} ({c['ci95'][0]:.2f}–{c['ci95'][1]:.2f})"

    names = " | ".join(f.name for f in fires)
    return [
        HEADLINE_START,
        f"| | {names} |",
        "|---|" + "---|" * len(fires),
        f"| Synthetic fires, location error (median): back-trace vs first-footprint centroid | {cells(lambda f: dist(syn(f)['summary_all_observations']))} |",
        f"| Synthetic fires, start-time error (median): back-trace vs √area back-extrapolation | {cells(lambda f: time(syn(f)['summary_all_observations']))} |",
        f"| The same with the first two perimeters held out: location; start time | {cells(lambda f: dist(syn(f)['summary']) + '; ' + time(syn(f)['summary']))} |",
        f"| 90% radius / interval contains the truth, on synthetic cases the calibration never saw | {cells(coverage)} |",
        f"| Unseen synthetic cases where the app would show a start time | {cells(shown)} |",
        f"| Real fire: estimated start time | {cells(real_start)} |",
        f"| Real hold-out: start-time error vs CAL FIRE (baseline) | {cells(lambda f: fmt_min(hold(f)['errors']['backtrace_time_error_min']) + ' (' + fmt_min(hold(f)['errors']['baseline_time_error_min']) + ')')} |",
        f"| CAL FIRE's reported point, distance outside the first mapped footprint | {cells(outside)} |",
        f"| Real fit with the HRRR wind field vs the old single ERA5 point (footprint IoU, spread-rate scale k) | {cells(wind)} |",
        f"| Hourly wind vs the nearest airport station: HRRR vs ERA5 | {cells(station)} |",
        f"| Odds ratio of destruction, fine-mesh vents vs coarse (95% CI) | {cells(lambda f: odds(f, 'vents'))} |",
        f"| Odds ratio, tile/metal/concrete roof vs asphalt/wood | {cells(lambda f: odds(f, 'roof'))} |",
        HEADLINE_END,
    ]


def write_headline(fires) -> None:
    text = README.read_text()
    if HEADLINE_START not in text:
        return
    a = text.index(HEADLINE_START)
    b = text.index(HEADLINE_END) + len(HEADLINE_END)
    README.write_text(text[:a] + "\n".join(headline(fires)) + text[b:])


def main() -> None:
    fires = [load_fire(f) for f in FIRES]
    lines = [
        "# Results",
        "",
        "Generated by `pipeline/tools/report.py` (`make report`) from the committed outputs in `web/public/data/`. "
        "Do not edit by hand.",
        "",
        "## Ignition back-trace: synthetic recovery benchmark",
        "",
    ]
    for f in fires:
        lines += synthetic_section(f)
    lines += ["## Ignition back-trace: real hold-out", "",
              "The model never sees the first two perimeters or CAL FIRE's reference. CAL FIRE's point is the "
              "reported incident location, not an investigated origin.", ""]
    for f in fires:
        lines += holdout_section(f)
    lines += ["## Wind ablation: does the HRRR field help?", ""]
    for f in fires:
        lines += ablation_section(f)
    lines += ["## House-level construction associations", ""]
    for f in fires:
        lines += exposure_section(f)
    lines += ["## Data checks", ""]
    for f in fires:
        lines += data_section(f)
    lines += ["## Analyst eval", ""] + analyst_section(fires)
    OUT.write_text("\n".join(lines).rstrip() + "\n")
    write_headline(fires)
    print(f"wrote {OUT} and the README headline table")


if __name__ == "__main__":
    main()
